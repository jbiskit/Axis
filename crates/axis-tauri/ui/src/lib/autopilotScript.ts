/**
 * Generates a Windows Autopilot enrolment script.
 *
 * This is a thin wrapper around `Get-WindowsAutopilotInfo` (Michael Niehaus /
 * Microsoft, PowerShell Gallery). That script already implements hardware hash
 * collection, online registration, group tags, `-AddToGroup`, assignment
 * waiting and reboot — so this generator only resolves paths and passes the
 * chosen switches through.
 */

export type AutopilotScriptOptions = {
  /** Register the device with Intune during the run. */
  registerOnline: boolean;
  /** Write the hardware hash to a CSV for later import. */
  exportHash: boolean;
  /** Optional group tag applied to the device. */
  groupTag: string;
  /** Optional Entra group the device is added to after registration. */
  groupName: string;
  /** Install the collector from the PowerShell Gallery if it is missing. */
  installCollector: boolean;
  /** Wait for the deployment profile to be assigned. */
  assign: boolean;
  /** Reboot once the profile is assigned (requires `assign`). */
  reboot: boolean;
  /**
   * CSV file name written under `<script folder>\Export` (export only).
   * The folder is resolved at run time from `$PSScriptRoot`, so the script
   * travels with its output.
   */
  exportFileName: string;
};

export function defaultAutopilotScriptOptions(): AutopilotScriptOptions {
  return {
    registerOnline: true,
    exportHash: false,
    groupTag: "",
    groupName: "",
    installCollector: true,
    assign: false,
    reboot: false,
    exportFileName: "export.csv",
  };
}

function psQuote(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

/** Builds the full `.ps1` contents for the chosen options. */
export function buildAutopilotScript(options: AutopilotScriptOptions): string {
  const {
    registerOnline,
    exportHash,
    groupTag,
    groupName,
    installCollector,
    assign,
    reboot,
    exportFileName,
  } = options;

  const lines: string[] = [];

  lines.push("<#");
  lines.push("  Windows Autopilot enrolment");
  lines.push("");
  if (registerOnline && exportHash) {
    lines.push("  Registers this device with Windows Autopilot and writes its hardware hash to a CSV.");
  } else if (registerOnline) {
    lines.push("  Registers this device with Windows Autopilot in the signed-in tenant.");
  } else {
    lines.push("  Collects this device's hardware hash and writes it to a CSV for later import.");
  }
  lines.push("");
  lines.push("  Wraps Get-WindowsAutopilotInfo (Microsoft, PowerShell Gallery).");
  lines.push("  Generated by Axis. Run in an elevated PowerShell session.");
  lines.push("#>");
  lines.push("");
  lines.push("$ErrorActionPreference = 'Stop'");
  lines.push("");

  if (installCollector) {
    lines.push("if (-not (Get-Command Get-WindowsAutopilotInfo -ErrorAction SilentlyContinue)) {");
    lines.push("    Write-Host 'Installing Get-WindowsAutopilotInfo…'");
    lines.push("    Install-Script -Name Get-WindowsAutopilotInfo -Force -Confirm:$false");
    lines.push("}");
    lines.push("");
  }

  lines.push("$collector = (Get-Command Get-WindowsAutopilotInfo -ErrorAction SilentlyContinue).Source");
  lines.push("if (-not $collector) {");
  lines.push("    throw 'Get-WindowsAutopilotInfo is required. Install it from the PowerShell Gallery and re-run.'");
  lines.push("}");
  lines.push("");

  if (exportHash) {
    lines.push("# The CSV lands in an Export folder beside this script.");
    lines.push("$scriptRoot = if ($PSScriptRoot) { $PSScriptRoot } else { (Get-Location).Path }");
    lines.push("$exportDir = Join-Path $scriptRoot 'Export'");
    lines.push(`$outputFile = Join-Path $exportDir ${psQuote(exportFileName.trim() || "export.csv")}`);
    lines.push("if (-not (Test-Path $exportDir)) {");
    lines.push("    New-Item -ItemType Directory -Path $exportDir -Force | Out-Null");
    lines.push("}");
    lines.push("");
  }

  lines.push("$collectorArgs = @{");
  if (registerOnline) lines.push("    Online = $true");
  if (exportHash) lines.push("    OutputFile = $outputFile");
  if (groupTag.trim()) lines.push(`    GroupTag = ${psQuote(groupTag.trim())}`);
  // The collector resolves the group by display name, not id.
  if (registerOnline && groupName.trim()) lines.push(`    AddToGroup = ${psQuote(groupName.trim())}`);
  if (registerOnline && assign) lines.push("    Assign = $true");
  if (registerOnline && assign && reboot) lines.push("    Reboot = $true");
  lines.push("}");
  lines.push("");

  lines.push("& $collector @collectorArgs");

  return `${lines.join("\n")}\n`;
}

/** Suggested file name for the generated script. */
export function autopilotScriptFileName(options: AutopilotScriptOptions): string {
  const tag = options.groupTag.trim().replace(/[^A-Za-z0-9._-]+/g, "-");
  const suffix = tag ? `-${tag}` : "";
  const action =
    options.registerOnline && options.exportHash
      ? "Online-Export"
      : options.registerOnline
        ? "Online"
        : "Export";
  return `Enable-Autopilot-${action}${suffix}.ps1`;
}
